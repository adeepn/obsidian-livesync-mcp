def apply(name):
    module_name, source, mutation, *count = MUTATIONS[name]
    module = __import__(module_name)
    path = ROOT / (module_name + '.py')
    text = path.read_text()
    if text.count(source) != (count[0] if count else 1):
        raise SystemExit(f'{name}: fragment found {text.count(source)} times in {module_name}.py')
    exec(compile(text.replace(source, mutation), str(path), 'exec'), module.__dict__)


def run(name):
    try:
        apply(name)
    except (SystemExit, AssertionError) as exc:
        print(f'{name}: mutation did not apply: {exc}', file=sys.stderr)
        sys.exit(3)
    import pytest
    sys.exit(pytest.main(['-p', 'no:cacheprovider', '-q', '--tb=no', *TESTS]))


if __name__ == '__main__':
    sys.path.insert(0, str(ROOT))
    if len(sys.argv) > 2 and sys.argv[1] == '--run':
        run(sys.argv[2])
    machine = '--json' in sys.argv[1:]
    survivors, broken = [], []
    for name in MUTATIONS:
        done = subprocess.run([sys.executable, __file__, '--run', name], cwd=ROOT,
                              capture_output=True, text=True)
        # pytest exits 1 when a test fails; 0 means every test passed; 3 means the
        # mutation no longer matches the source and the check itself is stale.
        (survivors if done.returncode == 0 else broken if done.returncode != 1 else []).append(name)
        lines = (done.stdout + done.stderr).strip().splitlines()
        verdict = lines[-1] if lines else ''
        state = 'SURVIVED' if done.returncode == 0 else 'STALE' if done.returncode == 3 else 'caught'
        summary = f'{state:8} {name}: {verdict}'
        print(json.dumps({'id': name, 'exit': done.returncode, 'state': state,
                          'summary': verdict}) if machine else summary, flush=True)
    print(json.dumps({'mutations': len(MUTATIONS), 'survivors': survivors, 'stale': broken}) if machine
          else f'{len(MUTATIONS) - len(survivors) - len(broken)}/{len(MUTATIONS)} mutations caught; '
               f'{len(survivors)} survived, {len(broken)} stale')
    sys.exit(1 if survivors or broken else 0)
